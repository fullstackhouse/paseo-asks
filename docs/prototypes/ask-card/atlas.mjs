// design-atlas engine: renders a UI atlas (index.html) from the feature's markdown and the
// per-area mockup modules. Copied into the atlas directory by init-atlas.mjs; never edited per
// project — configuration lives in generate.mjs.
//
// Text comes from the markdown, never from the generator:
//   - the UI map (`mapFile`): one "## <Letter> — <Label>" section per area with its view list
//     (a "Views: A1 Name, A2 Name." line or "- **A1 Name** (P1) — …" bullets), and a mermaid flow;
//   - cards files (`areaFiles`): "## <Id> <Name> (<phase>[, note])" sections with "- **Field.**"
//     bullets are view cards; every other "## " section (Area-wide, Decisions, …) is prose.
// Mockups come from state modules: `(kit) => ({ A1: [{ id: 's1', caption, html, notes? }] })`.
// The run fails when the markdown and the mockups disagree (see checkCoverage).
import fs from 'node:fs'
import path from 'node:path'

export const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')

