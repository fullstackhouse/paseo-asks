// ── prototype id / comments.js ──────────────────────────────────────────
// prototype.js drops a comments.js whose `prototypeId` differs from the page's
// `data-prototype-id`; the atlas writes comments.js when missing and refuses to run on a
// mismatch, so a rename cannot quietly hide committed review comments.
const commentsFile = (prototypeId) => `/* Committed prototype review operations.
 *
 * Do not edit this file by hand. Reviewers add comments in the prototype,
 * choose "Export for repository", replace this file, and commit it. Operations
 * are append-only and identified by id; delete operations are tombstones, so
 * merging reviewer exports cannot silently resurrect deleted feedback.
 *
 * \`prototypeId\` must stay equal to PROTOTYPE_ID in generate.mjs.
 */
window.__OM_PROTOTYPE_COMMENTS__ = {
  version: 2,
  prototypeId: '${prototypeId}',
  operations: []
};
`
const ID_IN_COMMENTS = /(?<![\w$])["']?prototypeId["']?\s*:\s*["']([^"']*)["']/
function declaredPrototypeId(source) {
  const code = source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '')
  const found = ID_IN_COMMENTS.exec(code)
  return found ? found[1] : null
}
function syncComments(outDir, prototypeId) {
  const file = path.join(outDir, 'comments.js')
  if (!fs.existsSync(file)) {
    fs.writeFileSync(file, commentsFile(prototypeId))
    return
  }
  const declared = declaredPrototypeId(fs.readFileSync(file, 'utf8'))
  if (declared !== prototypeId) {
    throw new Error(`comments.js declares prototypeId '${declared}', but this page is '${prototypeId}'. Fix one of them, then re-run.`)
  }
}

// ── markdown: a small parser for the spec files ─────────────────────────
// Supports what the UI specs use: ## sections, paragraphs, nested - and 1. lists with wrapped
// continuation lines, **bold**, *italic*, `code`, [links](...). Anything else renders as text.
const LIST_ITEM = /^(\s*)([-*]|\d+\.)\s+(.*)$/
const indentOf = (line) => line.match(/^\s*/)[0].length

export function sections(markdown) {
  const out = []
  let current = null
  let inFence = false
  for (const line of markdown.split('\n')) {
    if (line.startsWith('```')) inFence = !inFence
    if (!inFence && line.startsWith('## ')) {
      current = { title: line.slice(3).trim(), lines: [] }
      out.push(current)
    } else if (current) current.lines.push(line)
  }
  return out.map((s) => ({ title: s.title, body: s.lines.join('\n') }))
}

function parseList(lines, start, indent) {
  const ordered = /^\s*\d+\./.test(lines[start])
  const items = []
  let i = start
  while (i < lines.length) {
    const line = lines[i]
    if (!line.trim()) {
      let j = i + 1
      while (j < lines.length && !lines[j].trim()) j++
      const next = lines[j]
      if (next !== undefined && LIST_ITEM.test(next) && indentOf(next) >= indent) { i = j; continue }
      break
    }
    const ind = indentOf(line)
    const m = LIST_ITEM.exec(line)
    if (m && ind === indent) { items.push({ text: m[3], children: [] }); i++; continue }
    if (m && ind > indent && items.length) {
      const [sub, next] = parseList(lines, i, ind)
      items[items.length - 1].children.push(sub)
      i = next
      continue
    }
    if (!m && ind > indent && items.length) { items[items.length - 1].text += ' ' + line.trim(); i++; continue }
    break
  }
  return [{ type: ordered ? 'ol' : 'ul', items }, i]
}

export function parseBlocks(text) {
  const lines = text.split('\n')
  const blocks = []
  let i = 0
  while (i < lines.length) {
    const line = lines[i]
    if (!line.trim()) { i++; continue }
    if (line.startsWith('```')) {
      const buf = []
      i++
      while (i < lines.length && !lines[i].startsWith('```')) buf.push(lines[i++])
      i++
      blocks.push({ type: 'pre', text: buf.join('\n') })
      continue
    }
    if (LIST_ITEM.test(line)) {
      const [list, next] = parseList(lines, i, indentOf(line))
      blocks.push(list)
      i = next
      continue
    }
    const buf = []
    while (i < lines.length && lines[i].trim() && !LIST_ITEM.test(lines[i]) && !lines[i].startsWith('```')) buf.push(lines[i++].trim())
    blocks.push({ type: 'p', text: buf.join(' ') })
  }
  return blocks
}

const plain = (source) => source.replace(/\*\*|`|\*/g, '').replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')

function markdownRenderer(linkFor) {
  function inline(source) {
    const codes = []
    let s = source.replace(/`([^`]+)`/g, (_, c) => `\u0000${codes.push(c) - 1}\u0000`)
    s = esc(s)
    s = s.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (_, t, u) => `<a href="${linkFor(u)}">${t}</a>`)
    s = s.replace(/\*\*([^*]+)\*\*/g, '<b>$1</b>').replace(/(^|[^*\w])\*([^*\s][^*]*?)\*(?!\*)/g, '$1<i>$2</i>')
    return s.replace(/\u0000(\d+)\u0000/g, (_, n) => `<code>${esc(codes[Number(n)])}</code>`)
  }
  function renderList(list) {
    return `<${list.type}>${list.items.map((it) => `<li>${inline(it.text)}${it.children.map(renderList).join('')}</li>`).join('')}</${list.type}>`
  }
  function renderBlocks(blocks) {
    return blocks
      .map((b) => (b.type === 'p' ? `<p>${inline(b.text)}</p>` : b.type === 'pre' ? `<pre>${esc(b.text)}</pre>` : renderList(b)))
      .join('\n')
  }
  return { inline, renderList, renderBlocks }
}

// ── formats ─────────────────────────────────────────────────────────────
// Card heading: "## K3 Person home (M1)" or "(M1 credentials, P1 rest, dialog on K3)". The
// phase code becomes the badge, the words after it and the note after the comma a tag.
const VIEW_HEADING = /^([A-Z]\d+) (.+?) \(([MP]\d[^,)]*)(?:, (.+))?\)$/
const FIELD = /^\*\*([^*]+?)\.\*\*\s*(.*)$/
export const REQUIRED_FIELDS = ['Short', 'Extended', 'Get here', 'Shows', 'Variants', 'Edge cases']
// Cards-only areas (no mockups yet) may describe simple CRUD pages without Shows or Edge cases.
export const REQUIRED_FIELDS_CARDS_ONLY = ['Short', 'Extended', 'Get here', 'Variants']
// Fields in the card's left column; every other field goes to the right.
export const LEFT_FIELDS = ['Short', 'Extended', 'Feature', 'Get here', 'Shows']
const areaOf = (id) => id.replace(/\d+$/, '')

/**
 * Build the atlas: read the markdown, collect the states, check they agree, write index.html
 * (and comments.js on the first run). Throws with a list of problems when out of sync.
 *
 * config:
 *   outDir        atlas directory (index.html, comments.js are written here)
 *   specsDir      directory holding mapFile and the areaFiles
 *   prototypeId   = the atlas directory name; must match comments.js
 *   title         page title, e.g. "Time and Attendance — UI atlas"
 *   mapFile       the stage-1 UI map
 *   groups        optional [{ letter, label }] sidebar order and labels; default: the map's
 *                 "## X — Label (…)" sections in order
 *   areaFiles     [{ file, areas: ['L','H'], title, id?, mockups: bool, overview?: bool }];
 *                 `overview: true` (at most one) puts that file's prose on the overview page
 *                 instead of an area page
 *   mockupAreas   area letters in the mockup stage (strict: card ⇔ states)
 *   frameLabel    { L: '1440 desktop' } or one string, shown on each view header
 *   frameScales   { '--ka-scale': 1444 }: CSS variables set to fit a frame of that width
 *   states        state module(s): object, `(kit) => object`, or an array of them
 *   icons         extra icon paths { name: '<path …/>' }
 *   stylesheets   <link>ed in order
 *   overview      { intro(ctx), callout(ctx), flowTitle, flowNote, flowAreas, extra } — all
 *                 optional; intro/callout return HTML, extra is HTML placed under the flow;
 *                 ctx = { views, total, areaFiles: [{ ...cfg, views, states }], mapFile, specsHref, esc }
 *   requiredFields, requiredFieldsCardsOnly, leftFields   override the card field lists
 */
export function buildAtlas(config) {
  const {
    outDir,
    specsDir,
    prototypeId,
    title,
    mapFile,
    areaFiles,
    mockupAreas,
    frameLabel = {},
    frameScales = { '--ka-scale': 1444 },
    icons = {},
    stylesheets = ['tokens.css', 'components.css', 'screens.css', 'atlas.css', 'prototype.css'],
    overview: overviewConfig = {},
    requiredFields = REQUIRED_FIELDS,
    requiredFieldsCardsOnly = REQUIRED_FIELDS_CARDS_ONLY,
    leftFields = LEFT_FIELDS,
  } = config
  for (const key of ['outDir', 'specsDir', 'prototypeId', 'title', 'mapFile', 'areaFiles', 'mockupAreas']) {
    if (config[key] === undefined) throw new Error(`atlas config: "${key}" is required.`)
  }
  if (areaFiles.filter((f) => f.overview).length > 1) throw new Error('atlas config: at most one area file may have overview: true.')

  // Links in the specs are relative to specsDir; rewrite them relative to the atlas.
  const specsHref = path.relative(outDir, specsDir).split(path.sep).join('/') || '.'
  const linkFor = (url) => (/^([a-z][a-z0-9+.-]*:|#)/i.test(url) ? url : `${specsHref}/${url.replace(/^\.\//, '')}`)
  const { inline, renderList, renderBlocks } = markdownRenderer(linkFor)

  // ── icons ─────────────────────────────────────────────────────────────
  const ICONS = { ...BASE_ICONS, ...icons }
  const ic = (name) => {
    if (!ICONS[name]) throw new Error(`Unknown icon: ${name}`)
    return `<svg aria-hidden="true"><use href="#ic-${name}"/></svg>`
  }
  const sprite = () =>
    `<svg width="0" height="0" style="position:absolute" aria-hidden="true"><defs>${Object.entries(ICONS)
      .map(([k, d]) => `<symbol id="ic-${k}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${d}</symbol>`)
      .join('')}</defs></svg>`

  // ── states ────────────────────────────────────────────────────────────
  const kit = { ic, esc }
  const STATES = {}
  for (const source of [config.states || []].flat()) {
    const states = typeof source === 'function' ? source(kit) : source
    for (const [id, list] of Object.entries(states)) {
      if (STATES[id]) throw new Error(`States for ${id} are defined twice.`)
      STATES[id] = list
    }
  }

  // ── sources ───────────────────────────────────────────────────────────
  function readCards(file, required) {
    const all = sections(fs.readFileSync(path.join(specsDir, file), 'utf8'))
    const isView = (s) => /^[A-Z]\d+ /.test(s.title)
    const prose = all.filter((s) => !isView(s)).map((s) => ({ title: s.title, html: renderBlocks(parseBlocks(s.body)) }))
    const views = all.filter(isView).map((s) => {
      const m = VIEW_HEADING.exec(s.title)
      if (!m) throw new Error(`${file}: cannot parse heading "## ${s.title}" (expected "<Letter><n> Name (M1|P1[, note])").`)
      const list = parseBlocks(s.body).find((b) => b.type === 'ul')
      const fields = (list ? list.items : []).map((it) => {
        const f = FIELD.exec(it.text)
        if (!f) throw new Error(`${file} ${m[1]}: bullet does not start with "**Field.**": ${it.text.slice(0, 60)}`)
        return { name: f[1], text: f[2], children: it.children }
      })
      const missing = required.filter((n) => !fields.some((f) => f.name === n))
      if (missing.length) throw new Error(`${file} ${m[1]}: missing field(s) ${missing.join(', ')}.`)
      const code = m[3].slice(0, 2)
      const note = [m[3].slice(2).trim(), m[4]].filter(Boolean).join(', ')
      return { id: m[1], name: m[2], phase: code, note, fields, file }
    })
    return { file, views, prose }
  }

  // The map: areas (sidebar groups) with their view index, and the flow diagram.
  function readMap() {
    const source = fs.readFileSync(path.join(specsDir, mapFile), 'utf8')
    const all = sections(source)
    const byLetter = {}
    const found = []
    for (const s of all) {
      const m = /^([A-Z]) — (.+)$/.exec(s.title)
      if (m) { byLetter[m[1]] = s; found.push({ letter: m[1], label: plain(m[2]).replace(/\s*\(.*$/, '').trim() }) }
    }
    const groups = config.groups || found
    if (!groups.length) throw new Error(`${mapFile}: no "## <Letter> — <Area>" sections.`)
    for (const g of groups) if (!byLetter[g.letter]) throw new Error(`${mapFile}: no "## ${g.letter} — …" section.`)
    // Stage 2+: an index line "Views: L1 Live board, L2 Live work." Stage 1: bullets
    // "- **L1 Live board** (P1) — description".
    const index = {}
    const hasIndexLine = {}
    for (const g of groups) {
      const body = byLetter[g.letter].body
      const vm = /Views: (.+?)\.(?: |$)/.exec(body.replace(/\s+/g, ' '))
      if (vm) {
        hasIndexLine[g.letter] = true
        index[g.letter] = vm[1].split(/, /).map((t) => {
          const m = new RegExp(`^(${g.letter}\\d+) (.+)$`).exec(t.trim())
          if (!m) throw new Error(`${mapFile}: cannot parse view "${t}" in the ${g.letter} index line.`)
          return { id: m[1], name: m[2], phase: '', desc: '' }
        })
        continue
      }
      const list = parseBlocks(body).find((b) => b.type === 'ul')
      index[g.letter] = (list ? list.items : [])
        .map((it) => /^\*\*([A-Z]\d+) (.+?)\*\*\s*(.*)$/.exec(it.text))
        .filter(Boolean)
        .map(([, id, name, rest]) => {
          const phase = /^\(([^)]*)\)/.exec(rest)
          const phases = phase ? [...new Set(phase[1].match(/\b[MP]\d\b/g) || [])].join('/') : ''
          return { id, name: plain(name), phase: phases, desc: plain(rest.replace(/^\([^)]*\)\.?\s*/, '').replace(/^—\s*/, '')) }
        })
      if (!index[g.letter].length) throw new Error(`${mapFile}: no views parsed in the ${g.letter} section.`)
    }
    const fence = /```mermaid\n([\s\S]*?)```/.exec(source)
    if (!fence) throw new Error(`${mapFile}: no mermaid flow block.`)
    const labels = {}
    const edges = []
    const node = (tok) => {
      const m = /^([A-Za-z]\w*)(?:\[(.+)\])?$/.exec(tok.trim())
      if (!m) return null
      if (m[2]) labels[m[1]] = m[2]
      return m[1]
    }
    for (const raw of fence[1].split('\n')) {
      const line = raw.trim()
      if (!line || /^(flowchart|subgraph|end\b)/.test(line)) continue
      const parts = line.split(/\s*(-->(?:\|[^|]*\|)?|-\.[^.]*\.->)\s*/)
      let prev = node(parts[0])
      for (let i = 1; i + 1 < parts.length; i += 2) {
        const arrow = parts[i]
        const to = node(parts[i + 1])
        const label = (/\|([^|]*)\|/.exec(arrow) || /-\.([^.]*)\.->/.exec(arrow) || [])[1] || ''
        if (prev && to) edges.push({ from: prev, to, label: label.trim(), dotted: arrow.startsWith('-.') })
        prev = to
      }
    }
    const isArea = (s) => /^[A-Z] — /.test(s.title)
    const prose = all.filter((s) => !isArea(s) && s.title !== 'Flow').map((s) => ({ title: s.title, html: renderBlocks(parseBlocks(s.body)) }))
    return { groups, index, hasIndexLine, edges, labels, prose }
  }

  // ── consistency ───────────────────────────────────────────────────────
  function checkCoverage(map, files) {
    const problems = []
    const cardViews = files.flatMap(({ cards }) => cards.views)
    const mockupCards = files.filter(({ cfg }) => cfg.mockups).flatMap(({ cards }) => cards.views)
    for (const id of Object.keys(STATES)) if (!mockupAreas.includes(areaOf(id))) problems.push(`${id} has states but area ${areaOf(id)} is not in MOCKUP_AREAS`)
    for (const v of mockupCards) if (!STATES[v.id]) problems.push(`${v.id} is in a mockup-stage area but has no states`)
    for (const id of Object.keys(STATES)) if (!mockupCards.some((v) => v.id === id)) problems.push(`${id} has states but no "## ${id} …" card in any mockup-stage cards file`)
    for (const letter of mockupAreas) if (!files.some(({ cfg }) => cfg.areas.includes(letter))) problems.push(`area ${letter} is in MOCKUP_AREAS but no cards file is configured for it`)
    for (const { cfg, cards } of files) {
      for (const v of cards.views) {
        if (!cfg.areas.includes(areaOf(v.id))) problems.push(`${v.id} in ${cfg.file} is outside its areas (${cfg.areas.join(', ')})`)
        if (mockupAreas.includes(areaOf(v.id)) !== !!cfg.mockups) problems.push(`${v.id}: area ${areaOf(v.id)} ${cfg.mockups ? 'must be' : 'is'} in MOCKUP_AREAS but ${cfg.file} is configured with mockups: ${!!cfg.mockups}`)
      }
      for (const letter of cfg.areas) {
        const index = map.index[letter]
        if (!index) { problems.push(`${mapFile}: no "## ${letter} — …" area for ${cfg.file}`); continue }
        for (const v of index) {
          const c = cards.views.find((x) => x.id === v.id)
          if (!c) problems.push(`${v.id} is listed in ${mapFile} but has no card in ${cfg.file}`)
          else if (c.name !== v.name) problems.push(`${v.id} is "${v.name}" in ${mapFile} but "${c.name}" in ${cfg.file}`)
        }
        for (const c of cards.views.filter((x) => areaOf(x.id) === letter)) if (!index.some((v) => v.id === c.id)) problems.push(`${c.id} has a card in ${cfg.file} but is not listed in ${mapFile}`)
      }
    }
    for (const letter of Object.keys(map.hasIndexLine)) if (!files.some(({ cfg }) => cfg.areas.includes(letter))) problems.push(`${mapFile}: the ${letter} section has a "Views: …." index line but no cards file is configured for it`)
    const seenCards = new Set()
    for (const v of cardViews) {
      if (seenCards.has(v.id)) problems.push(`${v.id} has two cards`)
      seenCards.add(v.id)
    }
    for (const [id, list] of Object.entries(STATES)) {
      if (!list.length) problems.push(`${id} has no states`)
      const seen = new Set()
      for (const s of list) {
        if (!/^s\d+$/.test(s.id) || seen.has(s.id)) problems.push(`${id}: bad or duplicate state id ${s.id}`)
        if (!s.caption || typeof s.html !== 'string') problems.push(`${id}-${s.id}: a state needs a caption and html`)
        seen.add(s.id)
      }
    }
    if (problems.length) throw new Error(`Atlas out of sync with the spec:\n- ${problems.join('\n- ')}`)
  }

  // ── atlas page ────────────────────────────────────────────────────────
  const phaseBadge = (phase) => (phase ? `<span class="ka-phase ka-phase-${phase.split('/')[0]}">${esc(phase)}</span>` : '')
  const frameFor = (id) => (typeof frameLabel === 'string' ? frameLabel : frameLabel[areaOf(id)])
  const cardLink = (file, label = 'card text') => `<a class="ka-tag" href="${specsHref}/${file}">${label}: ${file}</a>`

  function card(view) {
    const field = (f) => `<div class="ka-field"><h4>${esc(f.name)}</h4><div class="ka-md">${f.text ? `<p>${inline(f.text)}</p>` : ''}${f.children.map(renderList).join('')}</div></div>`
    const left = view.fields.filter((f) => leftFields.includes(f.name))
    const right = view.fields.filter((f) => !leftFields.includes(f.name))
    return `<div class="ka-card"><div class="ka-col">${left.map(field).join('')}</div><div class="ka-col">${right.map(field).join('')}</div></div>`
  }

  function viewSection(view) {
    const states = STATES[view.id]
    const frame = frameFor(view.id)
    return `<section class="screen ka-view" id="${view.id}">
  <div class="screen-meta ka-view-head">
    <h2><span class="ka-id">${view.id}</span> ${esc(view.name)}</h2>
    <div class="ka-tags">${phaseBadge(view.phase)}${view.note ? `<span class="ka-tag">${esc(view.note)}</span>` : ''}<span class="ka-tag">${states.length} states${frame ? ` · ${esc(frame)}` : ''}</span>${cardLink(view.file)}</div>
  </div>
  ${card(view)}
  <nav class="ka-state-index" aria-label="${view.id} states">${states.map((s) => `<a href="#${view.id}-${s.id}"><code>${view.id}-${s.id}</code> ${esc(s.caption)}</a>`).join('')}</nav>
  ${states
    .map(
      (s) => `<figure class="ka-state" id="${view.id}-${s.id}">
    <figcaption><a class="ka-sid" href="#${view.id}-${s.id}">${view.id}-${s.id}</a><span>${esc(s.caption)}</span></figcaption>
    ${s.html}
    ${s.notes ? `<div class="notes">${s.notes.map((n, j) => `<div class="note"><b>${j + 1}</b><span>${n}</span></div>`).join('')}</div>` : ''}
  </figure>`,
    )
    .join('\n')}
</section>`
  }

  // A view with a card but no mockups yet (area still at stage 2).
  function cardsOnlySection(view) {
    return `<section class="screen ka-view" id="${view.id}">
  <div class="screen-meta ka-view-head">
    <h2><span class="ka-id">${view.id}</span> ${esc(view.name)}</h2>
    <div class="ka-tags">${phaseBadge(view.phase)}${view.note ? `<span class="ka-tag">${esc(view.note)}</span>` : ''}<span class="ka-tag ka-tag-pending">cards only · mockups pending</span>${cardLink(view.file)}</div>
  </div>
  ${card(view)}
  <div class="ka-callout ka-pending"><b>Mockups pending.</b> This area is at stage 2: the card above is the agreed description. Stage 3 adds one frame per state here.</div>
</section>`
  }

  function areaSection({ cfg, cards }) {
    return `<section class="screen ka-view" id="${cfg.id}">
  <div class="screen-meta ka-view-head"><h2>${esc(cfg.title)} — area rules</h2>
    <div class="ka-tags">${cfg.mockups ? '' : '<span class="ka-tag ka-tag-pending">cards only · mockups pending</span>'}${cardLink(cfg.file, 'source')}</div></div>
  ${cards.prose.map((p) => `<h3 class="ka-h3">${esc(p.title)}</h3><div class="ka-md ka-prose ka-narrow">${p.html}</div>`).join('\n')}
</section>`
  }

  function overview(map, files, ctx) {
    const rendered = new Map(files.flatMap(({ cards }) => cards.views).map((v) => [v.id, v]))
    const flowAreas = overviewConfig.flowAreas || files.find(({ cfg }) => cfg.overview)?.cfg.areas || map.groups.map((g) => g.letter)
    const flowViews = flowAreas.flatMap((letter) => map.index[letter] || [])
    const nodeLink = (id) => {
      const name = (map.labels[id] || id).replace(new RegExp(`^${id} `), '')
      return rendered.has(id) ? `<a href="#${id}"><code>${id}</code> ${esc(name)}</a>` : `<span class="ka-muted"><code>${id}</code> ${esc(name)}</span>`
    }
    const nodes = flowViews.map((v) => {
      const out = map.edges.filter((e) => e.from === v.id)
      const inc = map.edges.filter((e) => e.to === v.id)
      const phase = rendered.get(v.id)?.phase || v.phase
      const edge = (e, dir) => `<span class="ka-edge${e.dotted ? ' is-dotted' : ''}">${dir === 'out' ? '→' : '←'} ${nodeLink(dir === 'out' ? e.to : e.from)}${e.label ? ` <em>${esc(e.label)}</em>` : ''}</span>`
      return `<div class="ka-node"><div class="ka-node-head">${nodeLink(v.id)}${phaseBadge(phase)}</div>
      ${out.length ? `<div class="ka-edges"><span class="ka-dir">to</span>${out.map((e) => edge(e, 'out')).join('')}</div>` : ''}
      ${inc.length ? `<div class="ka-edges"><span class="ka-dir">from</span>${inc.map((e) => edge(e, 'in')).join('')}</div>` : ''}
    </div>`
    })
    // Overview prose: the overview file's (e.g. "Kiosk-wide", "Decisions"), else the map's decisions.
    const overviewFile = files.find(({ cfg }) => cfg.overview)
    const prose = overviewFile ? overviewFile.cards.prose : map.prose.filter((p) => /decisions/i.test(p.title))
    const mocked = files.filter(({ cfg }) => cfg.mockups).map(({ cfg }) => esc(cfg.title))
    const cardsOnly = files.filter(({ cfg }) => !cfg.mockups).map(({ cfg }) => esc(cfg.title))
    const intro = overviewConfig.intro
      ? overviewConfig.intro(ctx)
      : `${ctx.views} views with ${ctx.total} states.${mocked.length ? ` Mocked: ${mocked.join(', ')}.` : ''}${cardsOnly.length ? ` Cards only: ${cardsOnly.join(', ')}.` : ''} The remaining areas are listed from the map and are not designed yet.`
    const callout = overviewConfig.callout
      ? overviewConfig.callout(ctx)
      : `<b>Illustrative only.</b> Low-fi wireframes on the app’s tokens: they decide anatomy, states and copy intent, not the final look. All names and data are fictional. Card text is rendered from the cards files and the view list from <a href="${specsHref}/${mapFile}"><code>${esc(mapFile)}</code></a>: change the markdown and regenerate. Link to a view or a state by id: <code>#A1</code>, <code>#A1-s2</code>.`
    return `<section class="screen ka-view is-current" id="overview">
  <div class="screen-meta ka-view-head"><h2>${esc(title)}</h2>
    <p>${intro}</p></div>
  <div class="ka-callout">${callout}</div>
  <h3 class="ka-h3">${overviewConfig.flowTitle || 'Flow'}</h3>
  <p class="ka-muted">${overviewConfig.flowNote || 'From the map’s flow diagram. Dashed: a dotted edge in the diagram.'}</p>
  <div class="ka-flow">${nodes.join('')}</div>
  ${overviewConfig.extra ? `${overviewConfig.extra}\n  ` : ''}${prose.length ? `<div class="ka-two">
    ${prose.map((p) => `<div><h3 class="ka-h3">${esc(p.title)}</h3><div class="ka-md ka-prose">${p.html}</div></div>`).join('\n    ')}
  </div>` : ''}
</section>`
  }

  function sidebar(map, files) {
    const navItem = (v) => `<a href="#${v.id}" data-view="${v.id}"><span class="ka-id">${v.id}</span><span class="ka-name">${esc(v.name)}</span>${phaseBadge(v.phase)}</a>
      <div class="ka-states" data-view="${v.id}" hidden>${STATES[v.id].map((s) => `<a href="#${v.id}-${s.id}" title="${esc(s.caption)}"><code>${s.id}</code> ${esc(s.caption)}</a>`).join('')}</div>`
    const groups = map.groups
      .map((g) => {
        const source = files.find(({ cfg }) => cfg.areas.includes(g.letter))
        if (!source) {
          return `<div class="ka-group"><h3>${esc(g.label)}</h3>${map.index[g.letter]
            .map((v) => `<span class="ka-disabled" title="${esc(v.desc)}"><span class="ka-id">${v.id}</span><span class="ka-name">${esc(v.name)}<em>not designed yet</em></span>${phaseBadge(v.phase)}</span>`)
            .join('')}</div>`
        }
        const views = source.cards.views.filter((v) => areaOf(v.id) === g.letter)
        const rules = !source.cfg.overview && source.cfg.areas[0] === g.letter
          ? `<a href="#${source.cfg.id}" data-view="${source.cfg.id}"><span class="ka-id">·</span><span class="ka-name">Area rules and ${source.cards.prose.some((p) => p.title.startsWith('Decisions')) ? 'decisions' : 'open questions'}${source.cfg.mockups ? '' : '<em>cards only</em>'}</span></a>`
          : ''
        if (source.cfg.mockups) return `<div class="ka-group"><h3>${esc(g.label)}</h3>${rules}${views.map(navItem).join('')}</div>`
        return `<div class="ka-group"><h3>${esc(g.label)}</h3>${rules}${views
          .map((v) => `<a href="#${v.id}" data-view="${v.id}" class="is-cards-only"><span class="ka-id">${v.id}</span><span class="ka-name">${esc(v.name)}<em>cards only</em></span>${phaseBadge(v.phase)}</a>`)
          .join('')}</div>`
      })
      .join('')
    return `<aside class="ka-side"><nav class="ka-nav" aria-label="Views">
    <div class="ka-group"><a href="#overview" data-view="overview"><span class="ka-id">·</span><span class="ka-name">Overview: flow and rules</span></a></div>
    ${groups}
  </nav></aside>`
  }

  // Hash router: #A3 shows the view, #A3-s2 also scrolls to the state; frames scale to the column.
  const atlasJs = `(function () {
  var main = document.querySelector('.ka-main');
  var toolbar = document.querySelector('.doc-toolbar');
  var frames = ${JSON.stringify(frameScales)};
  function layout() {
    document.documentElement.style.setProperty('--ka-top', toolbar.offsetHeight + 'px');
    Object.keys(frames).forEach(function (name) {
      var s = Math.min(0.8, (main.clientWidth - 72) / frames[name]);
      document.documentElement.style.setProperty(name, Math.max(0.3, s).toFixed(4));
    });
  }
  function show() {
    var hash = decodeURIComponent(location.hash.slice(1)) || 'overview';
    var view = hash.replace(/-s\\d+$/, '');
    var section = document.getElementById(view);
    if (!section || !section.classList.contains('screen')) { view = 'overview'; section = document.getElementById('overview'); }
    document.querySelectorAll('.ka-main > .screen').forEach(function (s) { s.classList.toggle('is-current', s === section); });
    document.querySelectorAll('.ka-nav a[data-view]').forEach(function (a) {
      if (a.getAttribute('data-view') === view) a.setAttribute('aria-current', 'true'); else a.removeAttribute('aria-current');
    });
    document.querySelectorAll('.ka-states').forEach(function (el) { el.hidden = el.getAttribute('data-view') !== view; });
    document.querySelectorAll('.ka-states a').forEach(function (a) { a.classList.toggle('is-current', a.getAttribute('href') === '#' + hash); });
    var state = hash !== view ? document.getElementById(hash) : null;
    if (state) state.scrollIntoView({ block: 'start' }); else window.scrollTo(0, 0);
    window.dispatchEvent(new Event('resize'));
  }
  window.addEventListener('hashchange', show);
  window.addEventListener('resize', layout);
  layout();
  show();
})();`

  // ── build ─────────────────────────────────────────────────────────────
  syncComments(outDir, prototypeId)
  const map = readMap()
  const files = areaFiles.map((cfg) => ({
    cfg: { id: `area-${cfg.title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}`, ...cfg },
    cards: readCards(cfg.file, cfg.mockups ? requiredFields : requiredFieldsCardsOnly),
  }))
  for (const { cfg } of files) for (const letter of cfg.areas) if (!map.groups.some((g) => g.letter === letter)) throw new Error(`${cfg.file}: area ${letter} is not a group of ${mapFile}.`)
  checkCoverage(map, files)
  const views = Object.keys(STATES).length
  const total = Object.values(STATES).reduce((n, l) => n + l.length, 0)
  // ctx for overview.intro / callout: totals, and per area file its views and states counts.
  const areaCtx = files.map(({ cfg, cards }) => ({ ...cfg, views: cards.views.length, states: cards.views.reduce((n, v) => n + (STATES[v.id] || []).length, 0) }))
  const ctx = { views, total, areaFiles: areaCtx, mapFile, specsHref, esc }
  const areaNames = files.filter(({ cfg }) => cfg.mockups).map(({ cfg }) => cfg.title.toLowerCase()).join(', ')
  const html = `<!doctype html>
<html lang="en" data-prototype-id="${prototypeId}">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>${esc(title)}</title>
${stylesheets.map((href) => `<link rel="stylesheet" href="${href}" />`).join('\n')}
</head>
<body class="ka-body">
<!-- Generated by generate.mjs from ${[mapFile, ...areaFiles.map((f) => f.file)].join(', ')}. Do not edit. -->
${sprite()}
<div class="doc-toolbar">
  <strong style="font-size:0.875rem">${esc(title)}</strong>
  <span class="muted" style="font-size:0.75rem">${areaNames ? `${esc(areaNames)} · ` : ''}${views} views · ${total} states · illustrative only</span>
  <span style="flex:1"></span>
  <button class="btn btn-outline btn-sm" id="theme-toggle" type="button">${ic('sun')} Theme</button>
</div>
<div class="ka-layout">
${sidebar(map, files)}
<main class="doc ka-main">
<header class="doc-head" hidden><h1>${esc(title)}</h1></header>
${overview(map, files, ctx)}
${files.map((f) => [...(f.cfg.overview ? [] : [areaSection(f)]), ...f.cards.views.map(f.cfg.mockups ? viewSection : cardsOnlySection)].join('\n')).join('\n')}
</main>
</div>
<script>
(function () { var btn = document.getElementById('theme-toggle'); btn.addEventListener('click', function () { document.documentElement.classList.toggle('dark'); }); })();
</script>
<script src="comments.js"></script>
<script src="prototype.js"></script>
<script>
${atlasJs}
</script>
</body>
</html>
`
  fs.writeFileSync(path.join(outDir, 'index.html'), html)
  return { html, views, total }
}

// CLI wrapper for generate.mjs: build, print a one-line summary, exit 1 with the message on error.
export function runAtlas(config) {
  try {
    const { views, total } = buildAtlas(config)
    console.log(`wrote index.html: ${views} views, ${total} states`)
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error))
    process.exit(1)
  }
}
